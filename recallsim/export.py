# ---------------------------------------------------------------- generate
def generate(scale_name: str, seed: int, out_dir: Path, command: str | None = None) -> dict:
    scale = get_scale(scale_name)
    command = command or f"python -m recallsim generate --seed {seed} --scale {scale_name} --out <output-dir>"
    if out_dir.exists() and any(out_dir.iterdir()):
        if not (out_dir / "manifest.json").exists():
            raise FileExistsError(f"{out_dir} is not empty and is not a recallsim output folder")
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    clean, key = build_clean(scale, seed)
    shipped, truth = inject(clean, scale, seed)
    clean_n, shipped_n = _normalize(clean), _normalize(shipped)

    for t in TABLES:
        cols = [c.name for c in t.cols]
        _write(out_dir / "csv" / f"{t.name}.csv", _csv_text(cols, shipped_n[t.name]))
        _write(out_dir / "csv_clean" / f"{t.name}.csv", _csv_text(cols, clean_n[t.name]))
        _write(out_dir / "json" / f"{t.name}.json",
               json.dumps(shipped_n[t.name], indent=2, sort_keys=True) + "\n")
    _write(out_dir / "sql" / "seed.sql", _seed_sql(shipped_n))
    _write(out_dir / "sql" / "schema.sql", build_ddl() + "\n")
    _write(out_dir / "docs" / "DATA_DICTIONARY.md", build_markdown() + "\n")
    write_ground_truth(truth, out_dir / "ground_truth")
    _write(out_dir / "ground_truth" / "recall_answer_key.json", json.dumps(key, indent=2, sort_keys=True) + "\n")

    issues_shipped, issues_clean = validate(shipped), validate(clean)
    summary = {"shipped": write_summary(issues_shipped, shipped, out_dir / "validation" / "shipped"),
               "clean": write_summary(issues_clean, clean, out_dir / "validation" / "clean")}
    score = score_detection(issues_shipped, truth)
    _write(out_dir / "validation" / "detection_score.json", json.dumps(score, indent=2, sort_keys=True) + "\n")
    _write(out_dir / "metrics" / "recall_metrics.json", json.dumps(
        {"clean": all_metrics(clean, key), "shipped": all_metrics(shipped, key)}, indent=2, sort_keys=True) + "\n")

    files = {p: h for p, h in hash_tree(out_dir).items()}
    manifest = {
        "project": "recallsim", "generator_version": GENERATOR_VERSION, "seed": seed,
        "scale": scale_name, "scale_parameters": scale.__dict__, "as_of": AS_OF.isoformat(),
        "command": command, "row_counts": {t.name: len(shipped_n[t.name]) for t in TABLES},
        "clean_row_counts": {t.name: len(clean_n[t.name]) for t in TABLES},
        "anomalies": dict(sorted(Counter(t["issue_type"] for t in truth).items())),
        "provenance": {"external_data": "none", "personal_data": "none",
                       "source": "synthetic, generated by the code in this repository"},
        "files": {p: {"sha256": h, "bytes": (out_dir / p).stat().st_size} for p, h in sorted(files.items())},
    }
    _write(out_dir / "manifest.json", json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    _write(out_dir / "README.md", _readme(manifest, summary, score, command))
    return manifest


# ---------------------------------------------------------------- verify
def verify(scale_name: str, seed: int = SEED) -> dict:
    """Generate twice in two separate processes (different hash seeds) and compare every file."""
    result = {"scale": scale_name, "seed": seed}
    with tempfile.TemporaryDirectory() as tmp:
        trees = []
        for n, hash_seed in enumerate(("1", "4242")):
            out = Path(tmp) / f"run{n}"
            env = {**os.environ, "PYTHONHASHSEED": hash_seed}
            subprocess.run([sys.executable, "-m", "recallsim", "generate", "--seed", str(seed),
                            "--scale", scale_name, "--out", str(out)],
                           check=True, capture_output=True, env=env,
                           cwd=Path(__file__).resolve().parent.parent)
            trees.append(hash_tree(out))
            if n == 0:
                result["row_counts"] = json.loads((out / "manifest.json").read_text())["row_counts"]
        a, b = trees
        result["files"] = len(a)
        result["identical"] = a == b
        result["differences"] = sorted(k for k in a.keys() | b.keys() if a.get(k) != b.get(k))
        result["tree_sha256"] = hashlib.sha256(json.dumps(a, sort_keys=True).encode()).hexdigest()
    return result


def load_seed_sql(path: Path) -> sqlite3.Connection:
    conn = sqlite3.connect(":memory:")
    conn.executescript(path.read_text(encoding="utf-8"))
    return conn
