GENERATOR_VERSION = "1.0.0"


# ---------------------------------------------------------------- helpers
def _normalize(rows: dict[str, list[dict]]) -> dict[str, list[dict]]:
    """Fixed column order from the schema, floats rounded so text output never shows float noise."""
    out = {}
    for t in TABLES:
        cols = [c.name for c in t.cols]
        out[t.name] = [{c: (round(r[c], 6) if isinstance(r.get(c), float) else r.get(c)) for c in cols}
                       for r in rows[t.name]]
    return out


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def _csv_text(cols: list[str], rows: list[dict]) -> str:
    import io
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(cols)
    for r in rows:
        w.writerow(["" if r[c] is None else r[c] for c in cols])
    return buf.getvalue()


def _sql_value(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def _seed_sql(rows: dict[str, list[dict]]) -> str:
    lines = [
        "-- Seed data for the recall traceability dataset (SQLite).",
        "-- Foreign keys are switched off on purpose: this file holds the planted anomalies,",
        "-- and the ORPHAN_INPUT_LOT rows reference lots that do not exist.",
        build_ddl().rstrip(),
        "PRAGMA foreign_keys = OFF;",
        "BEGIN;",
    ]
    for t in TABLES:
        cols = [c.name for c in t.cols]
        head = f"INSERT INTO {t.name} ({', '.join(cols)}) VALUES "
        lines += [head + "(" + ", ".join(_sql_value(r[c]) for c in cols) + ");" for r in rows[t.name]]
    lines.append("COMMIT;")
    return "\n".join(lines) + "\n"


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def hash_tree(root: Path) -> dict[str, str]:
    return {p.relative_to(root).as_posix(): sha256_file(p)
            for p in sorted(root.rglob("*")) if p.is_file()}


# ---------------------------------------------------------------- README
